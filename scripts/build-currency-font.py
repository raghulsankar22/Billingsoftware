"""Rebuild the embedded currency subset from a supplied DejaVu Sans TTF.

Usage: python scripts/build-currency-font.py /path/to/DejaVuSans.ttf
Keep the source font's LICENSE alongside the generated module.
Upstream license: https://github.com/dejavu-fonts/dejavu-fonts/blob/master/LICENSE
Build dependency: fonttools (only needed when rebuilding the checked-in subset).
"""
import base64
import io
import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

font = TTFont(sys.argv[1])
assert 0x20B9 in font.getBestCmap(), "The source font must contain the rupee glyph"
subsetter = subset.Subsetter()
subsetter.populate(text="₹0123456789,. -Total Value:Loan Amount:")
subsetter.subset(font)
# Give the modified subset its own name as required by the font license.
for record in font["name"].names:
    if record.nameID in (1, 2, 3, 4, 6, 16, 17):
        name = "BillCurrency" if record.nameID != 2 else "Regular"
        record.string = name.encode(record.getEncoding())
buffer = io.BytesIO()
font.save(buffer)
encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
target = pathlib.Path(__file__).resolve().parents[1] / "src/lib/currency-font.ts"
target.write_text('// Generated by scripts/build-currency-font.py from DejaVu Sans.\n'
                  '// See currency-font.LICENSE for copyright and license.\n'
                  f'export const currencyFont = "{encoded}";\n', encoding="utf-8")
